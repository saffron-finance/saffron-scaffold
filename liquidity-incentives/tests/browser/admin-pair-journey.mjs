/** Shared browser journey for standalone and merged UIs. All API reads and
 * operator signatures hit the disposable server and real local EVM. */
export async function exercisePairPicker(page,fixture,expect){
  const before=(await fixture.database.catalog(true)).pairs.length
  await page.getByRole('button',{name:'Add pair',exact:true}).click()
  const form=page.getByRole('form',{name:'Add pair',exact:true})
  await expect(form.getByRole('button',{name:'Save pair',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:'Select reward token',exact:true}).click()
  await page.getByLabel('Search tokens').fill('CASHCAT')
  await page.getByRole('button',{name:/^Select CASHCAT 0x/}).click()
  await page.getByRole('button',{name:'Select quote token',exact:true}).click()
  await page.getByLabel('Search tokens').fill('CASHCAT')
  await expect(page.getByRole('button',{name:/^Select CASHCAT 0x/})).toBeDisabled()
  await page.getByLabel('Search tokens').fill('0x'+'1'.repeat(40))
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Cannot read supported ERC-20 metadata')
  await page.getByLabel('Search tokens').fill('WETH')
  const weth=page.getByRole('button',{name:/^Select WETH 0x/})
  await weth.focus();await page.keyboard.press('Enter')
  await expect(form.getByRole('button',{name:'1%',exact:true})).toHaveAttribute('aria-pressed','true')
  for(const fee of ['0.01%','0.05%','0.3%'])await expect(form.getByRole('button',{name:fee,exact:true})).toBeDisabled()
  await form.screenshot({path:'validation/admin-pair-desktop.png',animations:'disabled'})
  await page.getByRole('button',{name:'Swap reward and quote tokens'}).click()
  await expect(form.getByRole('button',{name:'Select reward token',exact:true})).toContainText('WETH')
  await expect(form.getByRole('button',{name:'Save pair',exact:true})).toBeEnabled()
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('button',{name:'Select quote token',exact:true}).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:'validation/admin-token-picker-mobile.png',animations:'disabled'})
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Select quote token',exact:true})).toBeFocused()
  await form.getByRole('button',{name:'Save pair',exact:true}).click()
  await expect(form).toHaveCount(0)
  const catalog=await fixture.database.catalog(true)
  expect(catalog.pairs.length).toBe(before+1)
  const added=catalog.pairs.find(p=>p.id.startsWith('pair-'))
  expect(added.token0.symbol).toBe('WETH');expect(added.token1.symbol).toBe('CASHCAT')
  expect(added.pool).toBe(fixture.chain.pool.toLowerCase());expect(added.feeTier).toBe(10000)
  expect(fixture.state.signs).toBeGreaterThan(0)
  expect(fixture.state.sends).toBe(0)
}
